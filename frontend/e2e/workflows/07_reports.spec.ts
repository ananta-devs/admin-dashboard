import { test, expect } from "../fixtures/auth.fixtures";
import crypto from "crypto";

test.describe("Workflow 7: Reports Subsystem API Contract Tests", () => {
  test("7.1 Report definition lifecycle (Create, Read, Update, List)", async ({
    page,
    baseURL,
    authenticatedUser,
  }) => {
    const origin = baseURL || "http://localhost:3000";

    // 1. Fetch CSRF token
    const csrfRes = await page.context().request.post(`${origin}/api/v1/auth/csrf-token`, {
      headers: { Origin: origin },
    });
    const { csrf_token: csrfToken } = await csrfRes.json();

    // 2. Create Report Definition
    const defTitle = `Quarterly Financial Performance ${Date.now()}`;
    const createRes = await page.context().request.post(`${origin}/api/v1/reports/definitions`, {
      data: {
        workspace_id: authenticatedUser.workspaceId,
        title: defTitle,
        description: "Comprehensive quarterly multi-section analytical report",
        format: "pdf",
        page_orientation: "portrait",
        page_size: "a4",
        header_text: "Confidential - Executive Eyes Only",
        footer_text: "Generated by VIBE Enterprise",
        include_table_of_contents: true,
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });

    expect(createRes.status()).toBe(201);
    const def = await createRes.json();
    expect(def.id).toBeDefined();
    expect(def.title).toBe(defTitle);
    expect(def.format).toBe("pdf");

    // 3. Read Report Definition
    const readRes = await page.context().request.get(`${origin}/api/v1/reports/definitions/${def.id}`);
    expect(readRes.status()).toBe(200);
    const readDef = await readRes.json();
    expect(readDef.id).toBe(def.id);

    // 4. Update Report Definition
    const updatedTitle = `${defTitle} - Revised`;
    const updateRes = await page.context().request.patch(`${origin}/api/v1/reports/definitions/${def.id}`, {
      data: {
        title: updatedTitle,
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });
    expect(updateRes.status()).toBe(200);
    const updatedDef = await updateRes.json();
    expect(updatedDef.title).toBe(updatedTitle);

    // 5. List Report Definitions
    const listRes = await page.context().request.get(`${origin}/api/v1/reports/definitions`);
    expect(listRes.status()).toBe(200);
    const list: Record<string, unknown>[] = await listRes.json();
    const found = list.find((item) => item.id === def.id);
    expect(found).toBeDefined();
  });

  test("7.2 Report section management and deterministic reordering", async ({
    page,
    baseURL,
    authenticatedUser,
  }) => {
    const origin = baseURL || "http://localhost:3000";

    const csrfRes = await page.context().request.post(`${origin}/api/v1/auth/csrf-token`, {
      headers: { Origin: origin },
    });
    const { csrf_token: csrfToken } = await csrfRes.json();

    // 1. Create Report Definition
    const defRes = await page.context().request.post(`${origin}/api/v1/reports/definitions`, {
      data: {
        workspace_id: authenticatedUser.workspaceId,
        title: `Section Test Report ${Date.now()}`,
        format: "pdf",
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });
    expect(defRes.status()).toBe(201);
    const def = await defRes.json();

    // 2. Add Section 1 (Markdown)
    const sec1Res = await page.context().request.post(`${origin}/api/v1/reports/definitions/${def.id}/sections`, {
      data: {
        section_type: "markdown",
        title: "Executive Summary",
        custom_content: "# Overview\nKey highlights for Q1.",
        sort_order: 0,
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });
    expect(sec1Res.status()).toBe(201);
    const sec1 = await sec1Res.json();

    // 3. Add Section 2 (Summary)
    const sec2Res = await page.context().request.post(`${origin}/api/v1/reports/definitions/${def.id}/sections`, {
      data: {
        section_type: "summary",
        title: "Key Metrics",
        sort_order: 1,
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });
    expect(sec2Res.status()).toBe(201);
    const sec2 = await sec2Res.json();

    // 4. Reorder sections (invert order: sec2 first, sec1 second)
    const reorderRes = await page.context().request.post(
      `${origin}/api/v1/reports/definitions/${def.id}/sections/reorder`,
      {
        data: {
          ordered_section_ids: [sec2.id, sec1.id],
        },
        headers: {
          "Content-Type": "application/json",
          "X-CSRF-Token": csrfToken,
          Origin: origin,
        },
      }
    );
    expect(reorderRes.status()).toBe(200);
    const reordered = await reorderRes.json();
    expect(reordered[0].id).toBe(sec2.id);
    expect(reordered[1].id).toBe(sec1.id);
  });

  test("7.3 Report run execution dispatch and download token security checks", async ({
    page,
    baseURL,
    authenticatedUser,
  }) => {
    const origin = baseURL || "http://localhost:3000";

    const csrfRes = await page.context().request.post(`${origin}/api/v1/auth/csrf-token`, {
      headers: { Origin: origin },
    });
    const { csrf_token: csrfToken } = await csrfRes.json();

    // 1. Create Report Definition
    const defRes = await page.context().request.post(`${origin}/api/v1/reports/definitions`, {
      data: {
        workspace_id: authenticatedUser.workspaceId,
        title: `Execution Test Report ${Date.now()}`,
        format: "pdf",
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });
    expect(defRes.status()).toBe(201);
    const def = await defRes.json();

    // 2. Trigger on-demand report execution
    const idempotencyKey = `e2e_report_${Date.now()}_${crypto.randomBytes(4).toString("hex")}`;
    const triggerRes = await page.context().request.post(`${origin}/api/v1/reports/definitions/${def.id}/runs`, {
      data: {
        idempotency_key: idempotencyKey,
        trigger_type: "manual",
      },
      headers: {
        "Content-Type": "application/json",
        "X-CSRF-Token": csrfToken,
        Origin: origin,
      },
    });

    // Must return HTTP 202 Accepted
    expect(triggerRes.status()).toBe(202);
    const run = await triggerRes.json();
    expect(run.id).toBeDefined();
    expect(run.report_definition_id).toBe(def.id);
    expect(["queued", "running", "succeeded"]).toContain(run.status);

    // 3. Query run status by ID
    const runStatusRes = await page.context().request.get(`${origin}/api/v1/reports/runs/${run.id}`);
    expect(runStatusRes.status()).toBe(200);
    const runStatus = await runStatusRes.json();
    expect(runStatus.id).toBe(run.id);

    // 4. Verify download token generation fails closed if run has not generated PDF artifact
    if (runStatus.status !== "succeeded") {
      const tokenRes = await page.context().request.post(`${origin}/api/v1/reports/runs/${run.id}/download-token`, {
        headers: {
          "X-CSRF-Token": csrfToken,
          Origin: origin,
        },
      });
      // Backend must reject with 400 or 422 ValidationError
      expect([400, 422]).toContain(tokenRes.status());
    }

    // 5. Unauthenticated / invalid token download must fail closed
    const forgedDownload = await page.context().request.get(`${origin}/api/v1/reports/download/forged-single-use-token-12345`);
    expect([400, 401, 403, 404, 422]).toContain(forgedDownload.status());
  });
});
